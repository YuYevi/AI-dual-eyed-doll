#!/usr/bin/env python3
"""Pack dual-eye GIF animations into a compact frame-delta asset."""
from __future__ import annotations

import argparse, hashlib, json, struct, subprocess, zlib
from pathlib import Path

WIDTH = HEIGHT = 160
FPS = 25
MAGIC = b"DEYEANIM"
VERSION = 1
EMOTIONS = ("calm", "happy", "surprised", "angry", "sad", "sleepy", "shy", "scared")
TABLE = struct.Struct("<12sHHIIII")
HEADER = struct.Struct("<8sHHII")
ASSET_TABLE = struct.Struct("<32sIIHH")
FRAME_HEADER = struct.Struct("<I")

def decode(path: Path) -> list[bytes]:
    raw = subprocess.check_output([
        "ffmpeg", "-v", "error", "-i", str(path),
        "-vf", f"scale={WIDTH}:{HEIGHT}:flags=lanczos",
        "-f", "rawvideo", "-pix_fmt", "rgb24", "-",
    ])
    rgb_size = WIDTH * HEIGHT * 3
    if len(raw) % rgb_size:
        raise ValueError(f"{path}: unexpected raw size {len(raw)}")
    frames = []
    for off in range(0, len(raw), rgb_size):
        rgb = raw[off:off + rgb_size]
        out = bytearray(WIDTH * HEIGHT * 2)
        j = 0
        for i in range(0, len(rgb), 3):
            r, g, b = rgb[i:i + 3]
            value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out[j:j + 2] = struct.pack("<H", value)
            j += 2
        frames.append(bytes(out))
    return frames

def pack_stream(frames: list[bytes]) -> bytes:
    previous = bytes(len(frames[0]))
    out = bytearray()
    for frame in frames:
        delta = bytes(a ^ b for a, b in zip(frame, previous))
        compressed = zlib.compress(delta, 9)
        out += FRAME_HEADER.pack(len(compressed))
        out += compressed
        previous = frame
    return bytes(out)

def package_assets(animation: bytes, srmodels: bytes | None = None) -> bytes:
    """Wrap animation (and optionally speech-recognition models) in the
    standard assets-partition container.

    The firmware loads the wake-word models through ``index.json``.  Keep the
    model entry optional so this helper remains useful for animation-only
    packages, while allowing the board package to retain the models generated
    by ``build_default_assets.py``.
    """
    index = {"version": 1}
    files = {"dual_eye.anim": animation}
    if srmodels is not None:
        files["srmodels.bin"] = srmodels
        index["srmodels"] = "srmodels.bin"
    files["index.json"] = json.dumps(index, separators=(",", ":")).encode("utf-8")
    entries = []
    merged = bytearray()
    for name in sorted(files, key=lambda value: (Path(value).suffix, value)):
        payload = files[name]
        entries.append((name, len(merged), len(payload)))
        merged += b"ZZ" + payload
    table = bytearray()
    for name, offset, length in entries:
        encoded = name.encode("utf-8")[:32].ljust(32, b"\0")
        table += ASSET_TABLE.pack(encoded, length, offset, 0, 0)
    combined = table + merged
    return struct.pack("<III", len(entries), sum(combined) & 0xFFFF, len(combined)) + combined


def read_existing_srmodels(path: Path) -> bytes | None:
    if not path.exists():
        return None
    package = path.read_bytes()
    if len(package) < 12:
        raise ValueError(f"{path}: truncated asset package")
    count, checksum, size = struct.unpack_from("<III", package)
    data_offset = 12 + count * ASSET_TABLE.size
    if data_offset > len(package) or size != len(package) - 12 or checksum != sum(package[12:]) & 0xFFFF:
        raise ValueError(f"{path}: invalid asset package")
    for index in range(count):
        name, length, offset, _, _ = ASSET_TABLE.unpack_from(package, 12 + index * ASSET_TABLE.size)
        if name.split(b"\0", 1)[0] != b"srmodels.bin":
            continue
        start = data_offset + offset
        if start + 2 + length > len(package) or package[start:start + 2] != b"ZZ":
            raise ValueError(f"{path}: invalid srmodels.bin entry")
        return package[start + 2:start + 2 + length]
    raise ValueError(f"{path}: srmodels.bin is missing")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=Path("docs/LCD资源动画/gif"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--package-output", type=Path)
    parser.add_argument(
        "--srmodels",
        type=Path,
        help="optional srmodels.bin generated by build_default_assets.py",
    )
    args = parser.parse_args()
    streams: dict[bytes, bytes] = {}
    records = []
    for emotion in EMOTIONS:
        left = decode(args.input / f"{EMOTIONS.index(emotion)+1:02d}_{emotion}_L.gif")
        right = decode(args.input / f"{EMOTIONS.index(emotion)+1:02d}_{emotion}_R.gif")
        if len(left) != len(right):
            raise ValueError(f"{emotion}: left/right frame count differs")
        left_stream = pack_stream(left)
        right_stream = pack_stream(right)
        left_key = hashlib.sha256(left_stream).digest()
        right_key = hashlib.sha256(right_stream).digest()
        streams.setdefault(left_key, left_stream)
        streams.setdefault(right_key, right_stream)
        records.append((emotion.encode(), len(left), left_key, right_key))
    header_size = HEADER.size + TABLE.size * len(records)
    offsets = {}
    cursor = header_size
    for key, stream in streams.items():
        offsets[key] = cursor
        cursor += len(stream)
    payload = bytearray(cursor)
    HEADER.pack_into(payload, 0, MAGIC, VERSION, len(records), HEADER.size, header_size)
    for index, (name, frame_count, left_key, right_key) in enumerate(records):
        TABLE.pack_into(payload, HEADER.size + index * TABLE.size,
                        name + b"\0" * (12 - len(name)), frame_count, FPS,
                        offsets[left_key], len(streams[left_key]),
                        offsets[right_key], len(streams[right_key]))
    for key, stream in streams.items():
        payload[offsets[key]:offsets[key] + len(stream)] = stream
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(payload)
    if args.package_output:
        args.package_output.parent.mkdir(parents=True, exist_ok=True)
        srmodels = (args.srmodels.read_bytes() if args.srmodels else
                    read_existing_srmodels(args.package_output))
        args.package_output.write_bytes(package_assets(payload, srmodels))
        print(f"wrote {args.package_output} ({args.package_output.stat().st_size} bytes)")
    print(f"wrote {args.output} ({len(payload)} bytes, {len(streams)} unique streams)")
    for emotion, frame_count, left_key, right_key in records:
        print(emotion.decode(), frame_count, offsets[left_key], len(streams[left_key]), offsets[right_key], len(streams[right_key]))

if __name__ == "__main__":
    main()
